import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'vite';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  root: packageRoot,
  configFile: false,
  logLevel: 'silent',
  build: {
    target: 'es2022',
    minify: true,
    sourcemap: false,
    write: false,
    lib: {
      entry: resolve(packageRoot, 'src/web-player-entry.ts'),
      formats: ['iife'],
      name: 'RPGNarrativeEngineWebPlayer',
      fileName: 'web-player',
    },
  },
});

const outputs = Array.isArray(result) ? result.flatMap((output) => output.output) : result.output;
const chunk = outputs.find((output) => output.type === 'chunk');
if (chunk === undefined) throw new Error('Vite did not produce the web player JavaScript chunk.');

const generated = `// Generated by scripts/generate-web-player.mjs. Do not edit by hand.\n// prettier-ignore\nexport const webPlayerJavaScript = ${JSON.stringify(chunk.code)};\n`;
await writeFile(resolve(packageRoot, 'src/web-player-bundle.generated.ts'), generated, 'utf8');
